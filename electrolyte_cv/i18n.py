from __future__ import annotations

_language = "en"


def get_language() -> str:
    return _language


def set_language(language: str) -> None:
    global _language
    _language = language if language in ("en", "zh") else "en"


def tr(text: str, *args, **kwargs) -> str:
    """Translate a display template, keeping file paths and values untouched."""
    template = ENGLISH.get(text, text) if _language == "en" else text
    return template.format(*args, **kwargs) if args or kwargs else template


_qt_translator = None


def install_qt_language() -> None:
    """Translate Qt-owned dialog buttons; English is Qt's source language."""
    global _qt_translator
    from .ui.qt_compat import QApplication, QLibraryInfo, QTranslator
    app = QApplication.instance()
    if app is None:
        return
    if _qt_translator is not None:
        app.removeTranslator(_qt_translator)
        _qt_translator.deleteLater()
        _qt_translator = None
    if _language == "zh":
        translator = QTranslator(app)
        directory = QLibraryInfo.path(QLibraryInfo.LibraryPath.TranslationsPath)
        if translator.load("qtbase_zh_CN", directory):
            app.installTranslator(translator)
            _qt_translator = translator


